/**
 * `en` is declared `as const` so every string becomes a literal type — this
 * lets tooling flag accidental key typos. But that means `typeof en` is far
 * too strict to reuse as the shape for other locales (ar.ts's Arabic strings
 * are, correctly, different literals). `Widen<T>` recursively relaxes every
 * string literal back to `string` while still preserving the exact object
 * shape, so `ar.ts` is still forced to match en.ts's structure (same keys,
 * same nesting) without being forced to match its English text.
 */
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? Widen<U>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

export type Translations = Widen<typeof en>;
